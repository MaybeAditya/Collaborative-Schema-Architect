/**
 * SQL generation helpers. Kept free of React/Yjs so the output can be tested in Node.
 */
export const SQL_TYPES = [
    'INTEGER',
    'TEXT',
    'VARCHAR(255)',
    'BOOLEAN',
    'DATE',
    'TIMESTAMP',
    'REAL',
    'DECIMAL(10,2)',
    'UUID',
];

const TYPE_ALIASES = {
    INT: 'INTEGER',
    'INT UNSIGNED': 'INTEGER',
    DATETIME: 'TIMESTAMP',
    DOUBLE: 'REAL',
    FLOAT: 'REAL',
    NUMERIC: 'DECIMAL(10,2)',
    'VARCHAR': 'VARCHAR(255)',
};

export function normalizeColumn(column = {}) {
    let rawType = String(column.type || 'TEXT').trim().toUpperCase();
    const legacyPrimaryKey = /\bPK\b/i.test(rawType);
    const legacyNotNull = /\bNOT\s+NULL\b/i.test(rawType);
    rawType = rawType.replace(/\bPK\b/gi, '').replace(/\bNOT\s+NULL\b/gi, '').trim();
    rawType = TYPE_ALIASES[rawType] || rawType;

    // Restrict generated types to the dropdown's known-safe SQL types. This also
    // prevents legacy document values from injecting arbitrary SQL fragments.
    const type = SQL_TYPES.includes(rawType) ? rawType : 'TEXT';
    return {
        name: column.name == null ? 'column' : String(column.name).trim(),
        type,
        primaryKey: Boolean(column.primaryKey || column.isPrimaryKey || legacyPrimaryKey),
        notNull: Boolean(column.notNull || column.notnull || legacyNotNull),
    };
}

function quoteIdentifier(identifier) {
    return `"${String(identifier).replace(/"/g, '""')}"`;
}

function toSnakeCase(value) {
    return String(value || 'table')
        .trim()
        .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
        .replace(/[^a-zA-Z0-9]+/g, '_')
        .replace(/^_+|_+$/g, '')
        .toLowerCase() || 'table';
}

/**
 * Convert table nodes and relationship edges into portable, quoted SQL.
 * Edges keep the app's existing convention: an edge from A to B means B gets
 * an FK column referencing A's primary key.
 */
export function generateSQL(nodes = [], edges = []) {
    if (!nodes.length) {
        return '-- No tables yet. Add a table to generate SQL.\n';
    }

    const nodeById = new Map(nodes.map((node) => [node.id, node]));
    const statements = ['-- Auto-generated by Collaborative Schema Architect'];
    const seenTableNames = new Set();

    for (const node of nodes) {
        const data = node.data || {};
        const tableName = String(data.label || 'Untitled_Table').trim() || 'Untitled_Table';
        const normalizedTableName = tableName.toLowerCase();
        if (seenTableNames.has(normalizedTableName)) {
            statements.push(`-- Skipped ${tableName}: another table already uses this name.`);
            continue;
        }
        seenTableNames.add(normalizedTableName);
        const columns = (Array.isArray(data.columns) ? data.columns : []).map((column, index) => {
            const normalized = normalizeColumn(column);
            return { ...normalized, name: normalized.name || `column_${index + 1}` };
        });

        if (!columns.length) {
            statements.push(`-- Skipped ${tableName}: add at least one column before generating SQL.`);
            continue;
        }

        const columnNameCounts = new Map();
        for (const column of columns) {
            const key = column.name.toLowerCase();
            columnNameCounts.set(key, (columnNameCounts.get(key) || 0) + 1);
        }
        const duplicateColumn = [...columnNameCounts.entries()].find(([, count]) => count > 1);
        if (duplicateColumn) {
            statements.push(`-- Skipped ${tableName}: duplicate column name ${quoteIdentifier(duplicateColumn[0])}.`);
            continue;
        }

        const definitions = [];
        const primaryKeys = columns.filter((column) => column.primaryKey);
        const hasCompositePrimaryKey = primaryKeys.length > 1;
        const existingNames = new Set(columns.map((column) => column.name.toLowerCase()));

        for (const column of columns) {
            let definition = `  ${quoteIdentifier(column.name)} ${column.type}`;
            if (column.primaryKey && !hasCompositePrimaryKey) {
                definition += ' PRIMARY KEY';
            } else if (column.notNull) {
                definition += ' NOT NULL';
            }
            definitions.push(definition);
        }

        // A single PK is inline. Multiple PK columns need a table-level constraint.
        if (hasCompositePrimaryKey) {
            definitions.push(`  PRIMARY KEY (${primaryKeys.map((column) => quoteIdentifier(column.name)).join(', ')})`);
        }

        const incomingEdges = edges.filter((edge) => edge.target === node.id);
        for (const edge of incomingEdges) {
            const sourceNode = nodeById.get(edge.source);
            if (!sourceNode) continue;

            const sourceData = sourceNode.data || {};
            const sourceColumns = (Array.isArray(sourceData.columns) ? sourceData.columns : []).map(normalizeColumn);
            const sourcePrimaryKeys = sourceColumns.filter((column) => column.primaryKey);
            const referencedColumn = sourcePrimaryKeys.length === 1 ? sourcePrimaryKeys[0] : null;
            // A composite primary key cannot be referenced by just one column.
            if (!referencedColumn || !referencedColumn.name) {
                if (sourcePrimaryKeys.length > 1) {
                    statements.push(`-- Skipped relationship to ${sourceData.label || 'source table'}: composite primary keys need an explicit multi-column relationship.`);
                }
                continue;
            }

            const sourceTableName = String(sourceData.label || 'Untitled_Table').trim() || 'Untitled_Table';
            const foreignKeyName = `${toSnakeCase(sourceTableName)}_id`;
            if (!existingNames.has(foreignKeyName.toLowerCase())) {
                definitions.push(`  ${quoteIdentifier(foreignKeyName)} ${referencedColumn.type}`);
                existingNames.add(foreignKeyName.toLowerCase());
            }
            definitions.push(
                `  FOREIGN KEY (${quoteIdentifier(foreignKeyName)}) REFERENCES ${quoteIdentifier(sourceTableName)} (${quoteIdentifier(referencedColumn.name)})`,
            );
        }

        statements.push(`CREATE TABLE ${quoteIdentifier(tableName)} (\n${definitions.join(',\n')}\n);`);
    }

    return `${statements.join('\n\n')}\n`;
}
